#!/usr/bin/env python3
"""Quoted footage and figures from the original (paper style): media.json → media_data.js.

    python3 media.py     # extract every entry in media.json (entries already up to date come from .media_cache/)

media.json is a list; each entry quotes one clip or one figure from the original, with its source:
  {"id": "ur5e-fold", "kind": "clip", "src": "raw/pi07-ur5e-fold.mp4", "from": 12.0, "to": 22.0,
   "fps": 15, "width": 960, "credit": "Physical Intelligence · π0.7 博客", "credit_en": "Physical Intelligence · π0.7 blog",
   "url": "https://www.pi.website/blog/pi07", "speed": "原片 1×", "note": "UR5e 叠衣服, 博客第 4 节视频"}
  {"id": "fig18", "kind": "image", "src": "raw/fig18.png", "crop": [0, 0, 1, .55], "width": 1400, "credit": "π0.7 论文 图 18", ...}

src is a local file (download it yourself into raw/, keep raw/ out of git). crop = [x, y, w, h] as fractions of the source.
Every entry needs credit and url: footage() prints the credit on screen for as long as the picture is visible.
Frames go into media_data.js as JPEG data URIs (not files next to index.html: file:// images taint the canvas and
record.mjs could no longer read it). build.py picks media_data.js up like any *_data.js; footage() draws from it.
Keep clips short (references/video-paper.md, "Quoting the original"): this script warns above 15 s per clip.
"""
import base64, glob, hashlib, json, os, subprocess, sys, tempfile

MAN, OUT = 'media.json', 'media_data.js'


def key(e):
    st = os.stat(e['src'])
    return hashlib.sha1(json.dumps([e, st.st_size, st.st_mtime], sort_keys=True).encode()).hexdigest()[:10]


def ff(*args):
    subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', *args], check=True)


def crop_vf(e):
    c = e.get('crop')
    return f"crop=iw*{c[2]}:ih*{c[3]}:iw*{c[0]}:ih*{c[1]}," if c else ''


def extract(e, tmp):
    w = int(e.get('width', 960 if e['kind'] == 'clip' else 1400))
    if e['kind'] == 'clip':
        fps = e.get('fps', 15)
        a, b = float(e['from']), float(e['to'])
        if b - a > 15: print(f"  WARNING {e['id']}: {b - a:.1f} s; quotes should stay short (≤ 15 s per clip)")
        ff('-ss', str(a), '-to', str(b), '-i', e['src'], '-an', '-vf', f"{crop_vf(e)}fps={fps},scale={w}:-2", '-q:v', '5', os.path.join(tmp, 'f%05d.jpg'))
    else:
        fps = 0
        ff('-i', e['src'], '-vf', f"{crop_vf(e)}scale={w}:-2", '-q:v', '3', '-frames:v', '1', os.path.join(tmp, 'f00001.jpg'))
    files = sorted(glob.glob(os.path.join(tmp, 'f*.jpg')))
    if not files: sys.exit(f"{e['id']}: ffmpeg produced no frames (check src / from / to)")
    probe = subprocess.run(['ffprobe', '-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=width,height', '-of', 'csv=p=0', files[0]],
                           capture_output=True, text=True, check=True).stdout.strip().split(',')
    frames = ['data:image/jpeg;base64,' + base64.b64encode(open(f, 'rb').read()).decode() for f in files]
    return {'kind': e['kind'], 'fps': fps, 'w': int(probe[0]), 'h': int(probe[1]), 'frames': frames,
            'credit': e['credit'], 'credit_en': e.get('credit_en', e['credit']), 'url': e['url'], 'speed': e.get('speed', '')}


def main():
    if not os.path.exists(MAN):
        print(f'no {MAN}; nothing to quote'); return
    man = json.load(open(MAN, encoding='utf-8'))
    ids = [e['id'] for e in man]
    if len(set(ids)) != len(ids): sys.exit('duplicate id in media.json')
    for e in man:
        miss = [k for k in ('id', 'kind', 'src', 'credit', 'url') if not e.get(k)]
        if miss: sys.exit(f"{e.get('id', '?')}: missing {', '.join(miss)} (credit and url are required)")
        if e['kind'] == 'clip' and ('from' not in e or 'to' not in e): sys.exit(f"{e['id']}: a clip needs from / to (seconds)")
        if not os.path.exists(e['src']): sys.exit(f"{e['id']}: {e['src']} not found")
    cache_dir = '.media_cache'; os.makedirs(cache_dir, exist_ok=True)
    media, keep = {}, set()
    for e in man:
        cp = os.path.join(cache_dir, f"{e['id']}.{key(e)}.json"); keep.add(os.path.abspath(cp))
        if os.path.exists(cp):
            media[e['id']] = json.load(open(cp)); continue
        with tempfile.TemporaryDirectory() as tmp:
            m = extract(e, tmp)
        json.dump(m, open(cp, 'w'))
        media[e['id']] = m
    for f in glob.glob(os.path.join(cache_dir, '*.json')):   # drop stale extractions (old crop / range, removed entries)
        if os.path.abspath(f) not in keep: os.remove(f)
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write('/* generated by media.py from media.json; do not edit */\nvar MEDIA_SRC = ')
        json.dump(media, fh, ensure_ascii=False)
        fh.write(';\n')
    total = os.path.getsize(OUT) / 1e6
    for i, m in media.items():
        n = len(m['frames'])
        print(f"  {i:<18} {m['kind']:<5} {m['w']}x{m['h']}  {n} frame{'s' if n > 1 else ''}" + (f" = {n / m['fps']:.1f} s" if m['fps'] else '') + f"  · {m['credit']}")
    print(f'{OUT}: {len(media)} entries, {total:.1f} MB')
    if total > 60: print('  WARNING: large; lower fps / width, or shorten clips')


if __name__ == '__main__':
    main()
